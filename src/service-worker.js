import { clientsClaim } from 'workbox-core';
import { ExpirationPlugin } from 'workbox-expiration';
import { precacheAndRoute, createHandlerBoundToURL } from 'workbox-precaching';
import { registerRoute } from 'workbox-routing';
import { CacheFirst, StaleWhileRevalidate } from 'workbox-strategies';
import { CacheableResponsePlugin } from 'workbox-cacheable-response';
// Generated by scripts/generate-public-precache.js (runs as "prebuild").
import publicPrecacheManifest from './publicPrecacheManifest.json';

clientsClaim();

precacheAndRoute([
  // Everything the webpack build produced: JS/CSS chunks, index.html, and
  // static/media assets (help page .md files).
  ...self.__WB_MANIFEST,
  // Tiles and help images in public/ are copied into build/ outside of
  // webpack, so they come from the generated list instead. Its revisions are
  // content hashes.
  ...publicPrecacheManifest.map(({ url, revision }) => ({
    url: process.env.PUBLIC_URL + url,
    revision,
  })),
]);

// App-shell-style routing: serve index.html for all navigation requests.
const fileExtensionRegexp = new RegExp('/[^/?]+\\.[^/]+$');
registerRoute(({ request, url }) => {
  // If this isn't a navigation, skip.
  if (request.mode !== 'navigate') {
    return false;
  }
  // If this is a URL that starts with /_, skip.
  if (url.pathname.startsWith('/_')) {
    return false;
  }
  // If this looks like a URL for a resource, because it contains a file
  // extension, skip.
  if (url.pathname.match(fileExtensionRegexp)) {
    return false;
  }
  // Return true to signal that we want to use the handler.
  return true;
}, createHandlerBoundToURL(process.env.PUBLIC_URL + '/index.html'));

// Google Fonts: cache the stylesheet with stale-while-revalidate and the font
// binaries cache-first so the Lato font keeps working offline.
registerRoute(
  ({ url }) => url.origin === 'https://fonts.googleapis.com',
  new StaleWhileRevalidate({ cacheName: 'google-fonts-stylesheets' })
);
registerRoute(
  ({ url }) => url.origin === 'https://fonts.gstatic.com',
  new CacheFirst({
    cacheName: 'google-fonts-webfonts',
    plugins: [
      new CacheableResponsePlugin({ statuses: [0, 200] }),
      new ExpirationPlugin({ maxEntries: 10, maxAgeSeconds: 365 * 24 * 60 * 60 }),
    ],
  })
);

// No route for the Umami tracker (analytics.konbamwa.net): analytics stops
// while offline, and neither the tracker nor src/analytics.js throws.

// This allows the web app to trigger skipWaiting via
// registration.waiting.postMessage({type: 'SKIP_WAITING'})
self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') {
    self.skipWaiting();
  }
});
